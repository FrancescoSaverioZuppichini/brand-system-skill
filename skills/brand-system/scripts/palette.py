# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///
# [Agent] OKLCH pigments in; hex, WCAG contrast, the tokens.css colour block and a markdown table
# out (input format in references/system.md). Exits 1 when it prints any PROBLEM.
# usage: uv run palette.py colors-in.json colors.json [--css colors.css] [--md colors.md] [--fit]
import argparse, json, math, sys
from pathlib import Path
from typing import NamedTuple, TypedDict

NEED = {"text": 4.5, "large": 3.0, "ui": 3.0, "decorative": 0.0}
ROLES = ["bg", "surface", "border", "text", "text-2", "primary", "on-primary", "accent",
         "on-accent", "focus"]
RGB = tuple[int, int, int]
Pair = tuple[str, str, str, str]  # fg, bg, use, kind
Roles = dict[str, dict[str, str]]  # theme → role → pigment
Table = dict[str, dict[str, str]]  # pigment → oklch, hex, role: the "tokens" of colors.json

Token = NamedTuple("Token", [("L", float), ("C", float), ("H", float), ("role", str)])
Row = TypedDict("Row", {"fg": str, "bg": str, "use": str, "kind": str, "ratio": float, "grade": str,
                        "ok": bool})

def to_linear(L: float, C: float, H: float) -> tuple[float, float, float]:
    a, b = C * math.cos(math.radians(H)), C * math.sin(math.radians(H))
    l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    return (4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
            -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
            -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s)

def in_gamut(L: float, C: float, H: float) -> bool:
    return all(-1e-4 <= v <= 1 + 1e-4 for v in to_linear(L, C, H))

def max_chroma(L: float, H: float) -> float:
    # [Agent] Bisection: the largest chroma that still fits sRGB at this lightness and hue.
    lo, hi = 0.0, 0.4
    for _ in range(30):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if in_gamut(L, mid, H) else (lo, mid)
    return lo

def to_srgb(L: float, C: float, H: float) -> RGB:
    linear = [min(max(v, 0), 1) for v in to_linear(L, C, H)]
    r, g, b = (12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055 for v in linear)
    return round(r * 255), round(g * 255), round(b * 255)

def luminance(rgb: RGB) -> float:
    channels = [v / 255 for v in rgb]
    r, g, b = (c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def contrast(a: RGB, b: RGB) -> float:
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)

def rate_pair(pair: Pair, rgb: dict[str, RGB]) -> Row:
    fg, bg, use, kind = pair
    ratio = round(contrast(rgb[fg], rgb[bg]), 2)
    grade = "AAA" if ratio >= 7 else "AA" if ratio >= 4.5 else "AA-large" if ratio >= 3 else "<3"
    return Row(fg=fg, bg=bg, use=use, kind=kind, ratio=ratio, grade=grade, ok=ratio >= NEED[kind])

def explain_fail(row: Row, fg: Token, bg: RGB) -> str:
    # [Agent] Walk the fg lightness away from the bg (same hue, chroma kept in sRGB) until the pair
    # passes, so a failure prints the number to type instead of "try again".
    need = NEED[row["kind"]]
    L, step = fg.L, -0.005 if luminance(to_srgb(fg.L, fg.C, fg.H)) <= luminance(bg) else 0.005
    while 0 <= L <= 1 and contrast(to_srgb(L, min(fg.C, max_chroma(L, fg.H)), fg.H), bg) < need:
        L += step
    hint = f"; {row['fg']} passes at L {round(L, 3)}" if 0 <= L <= 1 else ""
    return f"{row['fg']} on {row['bg']} = {row['ratio']} < {need} ({row['use']}){hint}"

def check_roles(roles: Roles, tokens: dict[str, Token], pairs: list[Pair]) -> list[str]:
    # [Agent] Each text role needs a declared pair on its theme's bg, or an empty pair list passes.
    declared = {(fg, bg) for fg, bg, _, kind in pairs if kind != "decorative"}
    problems = []
    for theme, mapping in roles.items():
        for role, pigment in mapping.items():
            where = f"role --{role} in {theme} points at"
            if role == pigment:
                problems.append(f"{where} a pigment with the same name: rename the pigment")
            elif pigment not in tokens:
                problems.append(f"{where} unknown pigment {pigment}")
        for role in ("text", "text-2", "text-3"):
            if role in mapping and (mapping[role], mapping.get("bg")) not in declared:
                problems.append(f"{theme}: no pair for --{role} on --bg")
    return problems

def role_vars(mapping: dict[str, str]) -> str:
    return "\n".join(f"  --{role}: var(--{pigment});" for role, pigment in mapping.items())

def render_css(table: Table, roles: Roles, default: str) -> str:
    # [Agent] [data-theme] works on any element (a dark card on a light page); the media query only
    # applies when nothing pinned a theme, so screenshots and mocks stay deterministic.
    css = ["/* generated by palette.py: edit colors-in.json, not this file */", ":root {"]
    css += [f"  --{k}: {t['oklch']}; /* {t['hex']} · {t['role']} */" for k, t in table.items()]
    css += [role_vars(roles[default]), "}"] if roles.get(default) else ["}"]
    for theme in [t for t in roles if t != default]:
        css.append(f'[data-theme="{theme}"] {{\n{role_vars(roles[theme])}\n}}')
        unpinned = f":root:not([data-theme]) {{\n{role_vars(roles[theme])}\n}}"
        css.append(f"@media (prefers-color-scheme: {theme}) {{ {unpinned} }}")
    if default in roles and len(roles) > 1:
        css.append(f'[data-theme="{default}"] {{\n{role_vars(roles[default])}\n}}')
    return "\n".join(css) + "\n"

def render_md(table: Table, rows: list[Row]) -> str:
    md = ["| Token | OKLCH | Hex | Role |", "|---|---|---|---|"]
    md += [f"| {k} | {t['oklch'][6:-1]} | {t['hex']} | {t['role']} |" for k, t in table.items()]
    md += ["", "| Pair | Use | Ratio | Grade |", "|---|---|---|---|"]
    for r in rows:
        grade = "decorative" if r["kind"] == "decorative" else r["grade"]
        md.append(f"| {r['fg']} on {r['bg']} | {r['use']} ({r['kind']}) | {r['ratio']} | {grade} |")
    return "\n".join(md) + "\n"

def main() -> None:
    ap = argparse.ArgumentParser()
    for name in ("spec", "out", "--css", "--md"):
        ap.add_argument(name)
    ap.add_argument("--fit", action="store_true", help="clamp chroma into sRGB instead of failing")
    a = ap.parse_args()
    spec = json.loads(Path(a.spec).read_text())
    roles, default, problems = spec.get("roles", {}), spec.get("default", "light"), []
    tokens = {k: Token(*v) for k, v in spec["tokens"].items()}
    for k, t in tokens.items():
        if in_gamut(t.L, t.C, t.H):
            continue
        mc = max_chroma(t.L, t.H)
        if a.fit:
            print(f"fit   {k}: chroma {t.C} → {mc:.3f} (sRGB limit at L {t.L}, H {t.H})")
            tokens[k] = t._replace(C=round(mc - 0.001, 3))
        else:
            limit = f"max chroma at L {t.L} H {t.H} is {mc:.3f}"
            problems.append(f"{k}: outside sRGB; {limit} (or run with --fit)")
    pairs: list[Pair] = []
    for fg, bg, use, *kind in spec.get("pairs", []):
        if fg in tokens and bg in tokens:
            pairs.append((fg, bg, use, kind[0] if kind else "text"))
        else:
            problems.append(f"pair {fg} on {bg} ({use}) names an unknown pigment")
    if not roles and not any(kind == "text" for *_, kind in pairs):
        problems.append("no text pair: add at least one [fg, bg, use] pair for body text")
    rgb = {k: to_srgb(t.L, t.C, t.H) for k, t in tokens.items()}
    rows = [rate_pair(pair, rgb) for pair in pairs]
    problems += [explain_fail(r, tokens[r["fg"]], rgb[r["bg"]]) for r in rows if not r["ok"]]
    problems += check_roles(roles, tokens, pairs)
    table = {k: {"oklch": f"oklch({t.L:.3f} {t.C:.3f} {t.H:g})", "hex": "#%02X%02X%02X" % rgb[k],
                 "role": t.role} for k, t in tokens.items()}
    out = {"tokens": table, "roles": roles, "default": default, "contrast": rows}
    Path(a.out).write_text(json.dumps(out, indent=1))
    if a.css:
        Path(a.css).write_text(render_css(table, roles, default))
    if a.md:
        Path(a.md).write_text(render_md(table, rows))
    for k, t in table.items():
        print(f"{k:20} {t['hex']}  {t['oklch']}")
    for r in rows:
        verdict = "decor" if r["kind"] == "decorative" else "ok" if r["ok"] else "FAIL"
        pair = f"{r['fg']:18} on {r['bg']:18}"
        print(f"{pair} {r['ratio']:5.2f}  {r['grade']:8} {verdict:5} {r['use']}")
    for theme, mapping in roles.items():
        if missing := [role for role in ROLES if role not in mapping]:
            print(f"warn  {theme} has no role {', '.join(missing)}")
    if problems:
        print("\nPROBLEMS:\n" + "\n".join(problems))
        sys.exit(1)

if __name__ == "__main__":
    main()
